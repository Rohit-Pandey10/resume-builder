import { sanitizeUrl, getDisplayUrl } from './urlHelper.js';
import { sanitizeSectionOrder } from './bulletHelper.js';

/**
 * Escapes reserved LaTeX characters in dynamic text.
 * CRITICAL RULE: Backslash '\' MUST be replaced first before any other character.
 *
 * @param {string} str - Raw user input text
 * @returns {string} - LaTeX-safe escaped string
 */
const LATEX_ESCAPE_MAP = {
  '\\': '\\textbackslash{}',
  '#': '\\#',
  '$': '\\$',
  '%': '\\%',
  '&': '\\&',
  '_': '\\_',
  '{': '\\{',
  '}': '\\}',
  '~': '\\textasciitilde{}',
  '^': '\\textasciicircum{}',
};

/**
 * Escapes reserved LaTeX characters in dynamic text.
 * Prevents double-escaping and cleanly maps all reserved characters.
 *
 * @param {string} str - Raw user input text
 * @returns {string} - LaTeX-safe escaped string
 */
export function escapeLatex(str) {
  if (str === null || str === undefined) return '';
  return String(str).replace(/[\\#$%&_{}~^]/g, (match) => LATEX_ESCAPE_MAP[match] || match);
}

/**
 * Formats a LaTeX hyperlink without escaping the raw URL destination.
 * CRITICAL RULE: In \href{RAW_URL}{DISPLAY_TEXT}, NEVER escape '_', '&', or '%'
 * inside the first parameter (RAW_URL). Only escape the DISPLAY_TEXT.
 *
 * @param {string} rawUrl - Unescaped URL target
 * @param {string} displayText - Display label to escape
 * @returns {string} - LaTeX \href command
 */
export function formatHref(rawUrl, displayText) {
  if (!rawUrl || !rawUrl.trim()) return '';
  const cleanUrl = sanitizeUrl(rawUrl);
  if (!cleanUrl) return '';
  const label = displayText ? escapeLatex(displayText.trim()) : escapeLatex(getDisplayUrl(cleanUrl));
  return `\\href{${cleanUrl}}{\\underline{${label}}}`;
}

/**
 * Generates an ATS-compliant Jake's Resume .tex document from a profile object.
 *
 * @param {object} profile - ResumeProfile document
 * @returns {string} - Complete valid LaTeX source code
 */
export function generateLatex(profile) {
  if (!profile) return '% No profile data provided';

  const {
    basics = {},
    education = [],
    experience = [],
    projects = [],
    skills = {},
    customSections = [],
    sectionOrder,
  } = profile;

  const order = sanitizeSectionOrder(sectionOrder);

  // Filter only enabled entries (defaults to true if enabled is undefined)
  const activeEdu = (education || []).filter((e) => e && e.enabled !== false);
  const activeExp = (experience || []).filter((e) => e && e.enabled !== false);
  const activeProj = (projects || []).filter((p) => p && p.enabled !== false);

  // Spacing refinement: If total entry count across projects and experience is low (< 4 entries),
  // use \vspace{-2pt} so the single-page content breathes and fills the page proportionally.
  const totalEntries = activeExp.length + activeProj.length;
  const isLightResume = totalEntries < 4;
  const itemEndSpacing = isLightResume ? '\\vspace{-2pt}' : '\\vspace{-5pt}';

  // 1. Header Contact Line
  const contactParts = [];
  if (basics.phone && typeof basics.phone === 'string' && basics.phone.trim()) {
    contactParts.push(escapeLatex(basics.phone.trim()));
  }
  if (basics.email && typeof basics.email === 'string' && basics.email.trim()) {
    const cleanEmail = basics.email.trim();
    contactParts.push(`\\href{mailto:${cleanEmail}}{\\underline{${escapeLatex(cleanEmail)}}}`);
  }
  if (basics.linkedinUrl && typeof basics.linkedinUrl === 'string' && basics.linkedinUrl.trim()) {
    const cleanUrl = sanitizeUrl(basics.linkedinUrl);
    if (cleanUrl) {
      const label = getDisplayUrl(cleanUrl, 'linkedin');
      if (label) {
        contactParts.push(`\\href{${cleanUrl}}{\\underline{${escapeLatex(label)}}}`);
      }
    }
  }
  if (basics.githubUrl && typeof basics.githubUrl === 'string' && basics.githubUrl.trim()) {
    const cleanUrl = sanitizeUrl(basics.githubUrl);
    if (cleanUrl) {
      const label = getDisplayUrl(cleanUrl, 'github');
      if (label) {
        contactParts.push(`\\href{${cleanUrl}}{\\underline{${escapeLatex(label)}}}`);
      }
    }
  }
  if (basics.portfolioUrl && typeof basics.portfolioUrl === 'string' && basics.portfolioUrl.trim()) {
    const cleanUrl = sanitizeUrl(basics.portfolioUrl);
    if (cleanUrl) {
      const label = getDisplayUrl(cleanUrl, 'portfolio');
      if (label) {
        contactParts.push(`\\href{${cleanUrl}}{\\underline{${escapeLatex(label)}}}`);
      }
    }
  }

  const cleanContactParts = contactParts.filter(Boolean);
  const contactLine = cleanContactParts.length > 0
    ? ` \\\\ \\vspace{1pt}\n    \\small ${cleanContactParts.join(' $|$ ')}`
    : '';

  // 2. Base Template Header with Jake's Resume Macros & Packages
  let tex = `%-------------------------
% Resume in LaTeX
% Generated by JakeResume Builder
% ATS-compliant Jake's Resume standard format
%------------------------

\\documentclass[letterpaper,11pt]{article}

\\usepackage{latexsym}
\\usepackage[empty]{fullpage}
\\usepackage{titlesec}
\\usepackage{marvosym}
\\usepackage[usenames,dvipsnames]{color}
\\usepackage{verbatim}
\\usepackage{enumitem}
\\usepackage[hidelinks]{hyperref}
\\usepackage{fancyhdr}
\\usepackage[english]{babel}
\\usepackage{tabularx}
\\input{glyphtounicode}

\\pagestyle{fancy}
\\fancyhf{}
\\fancyfoot{}
\\renewcommand{\\headrulewidth}{0pt}
\\renewcommand{\\footrulewidth}{0pt}

% Adjust margins
\\addtolength{\\oddsidemargin}{-0.5in}
\\addtolength{\\evensidemargin}{-0.5in}
\\addtolength{\\textwidth}{1in}
\\addtolength{\\topmargin}{-.5in}
\\addtolength{\\textheight}{1.0in}

\\urlstyle{same}

\\raggedbottom
\\raggedright
\\setlength{\\tabcolsep}{0in}

% Sections formatting
\\titleformat{\\section}{
  \\vspace{-4pt}\\scshape\\raggedright\\large
}{}{0em}{}[\\color{black}\\titlerule \\vspace{-5pt}]

% Ensure that generate pdf is machine readable/ATS parsable
\\pdfgentounicode=1

%-------------------------
% Custom commands
\\newcommand{\\resumeItem}[1]{
  \\item\\small{
    {#1 \\vspace{-2pt}}
  }
}

\\newcommand{\\resumeSubheading}[4]{
  \\vspace{-2pt}\\item
    \\begin{tabular*}{0.97\\textwidth}[t]{l@{\\extracolsep{\\fill}}r}
      \\textbf{#1} & #2 \\\\
      \\textit{\\small#3} & \\textit{\\small #4} \\\\
    \\end{tabular*}\\vspace{-7pt}
}

\\newcommand{\\resumeSubSubheading}[2]{
    \\item
    \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}
      \\textit{\\small#1} & \\textit{\\small #2} \\\\
    \\end{tabular*}\\vspace{-7pt}
}

\\newcommand{\\resumeProjectHeading}[2]{
    \\vspace{-2pt}\\item
    \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}
      \\small#1 & #2 \\\\
    \\end{tabular*}\\vspace{-7pt}
}

\\newcommand{\\resumeSubHeadingListStart}{\\begin{itemize}[leftmargin=0.15in, label={}]}
\\newcommand{\\resumeSubHeadingListEnd}{\\end{itemize}}
\\newcommand{\\resumeItemListStart}{\\begin{itemize}}
\\newcommand{\\resumeItemListEnd}{\\end{itemize}${itemEndSpacing}}

%-------------------------------------------
%%%%%%  RESUME STARTS HERE  %%%%%%%%%%%%%%%%%%%%%%%%%%%%

\\begin{document}

%----------HEADING----------
\\begin{center}
    \\textbf{\\Huge \\scshape ${escapeLatex(basics.fullName || 'Your Name')}}${contactLine}
\\end{center}
`;

  // Section renderers aligned with dynamic sectionOrder
  const renderEducation = () => {
    if (activeEdu.length === 0) return '';
    let out = `\n%-----------EDUCATION-----------\n\\section{Education}\n  \\resumeSubHeadingListStart\n`;
    activeEdu.forEach((edu) => {
      const inst = escapeLatex(edu.institution || '');
      const loc = escapeLatex(edu.location || '');
      const degreeText = edu.gpa && edu.gpa.trim()
        ? `${edu.degree || ''} (GPA: ${edu.gpa.trim()})`
        : (edu.degree || '');
      const deg = escapeLatex(degreeText);
      const dates = [edu.startDate, edu.endDate].filter(Boolean).map((s) => s.trim()).join(' -- ');

      out += `    \\resumeSubheading\n      {${inst}}{${loc}}\n      {${deg}}{${escapeLatex(dates)}}\n`;
    });
    out += `  \\resumeSubHeadingListEnd\n`;
    return out;
  };

  const renderExperience = () => {
    if (activeExp.length === 0) return '';
    let out = `\n%-----------EXPERIENCE-----------\n\\section{Experience}\n  \\resumeSubHeadingListStart\n`;
    activeExp.forEach((exp) => {
      const company = escapeLatex(exp.company || '');
      const role = escapeLatex(exp.role || '');
      const loc = escapeLatex(exp.location || '');
      const dates = [exp.startDate, exp.endDate].filter(Boolean).map((s) => s.trim()).join(' -- ');

      out += `    \\resumeSubheading\n      {${role}}{${escapeLatex(dates)}}\n      {${company}}{${loc}}\n`;

      const validBullets = (exp.bullets || [])
        .map((b) => (typeof b === 'string' ? { text: b, enabled: true } : b))
        .filter((b) => b && b.enabled !== false && ((typeof b === 'string' && b.trim()) || (b.text && String(b.text).trim()) || (b.bullet && String(b.bullet).trim())));

      if (validBullets.length > 0) {
        out += `      \\resumeItemListStart\n`;
        validBullets.forEach((b) => {
          const rawBullet = typeof b === 'string' ? b : (b.text ?? b.bullet ?? '');
          out += `        \\resumeItem{${escapeLatex(String(rawBullet).trim())}}\n`;
        });
        out += `      \\resumeItemListEnd\n`;
      }
    });
    out += `  \\resumeSubHeadingListEnd\n`;
    return out;
  };

  const renderProjects = () => {
    if (activeProj.length === 0) return '';
    let out = `\n%-----------PROJECTS-----------\n\\section{Projects}\n  \\resumeSubHeadingListStart\n`;
    activeProj.forEach((proj) => {
      const techStack = (proj.techStack || []).filter(Boolean).map((t) => t.trim());
      const techText = techStack.length > 0
        ? `$|$ \\emph{${escapeLatex(techStack.join(', '))}}`
        : '';

      const titleEscaped = escapeLatex(proj.title || 'Untitled Project');
      let titleFormatted = `\\textbf{${titleEscaped}}`;
      if (proj.link && proj.link.trim()) {
        const cleanUrl = sanitizeUrl(proj.link);
        if (cleanUrl) {
          titleFormatted = `\\href{${cleanUrl}}{\\underline{${titleEscaped}}}`;
        }
      }

      const headingFirst = `${titleFormatted} ${techText}`.trim();

      out += `    \\resumeProjectHeading\n      {${headingFirst}}{}\n`;

      const validBullets = (proj.bullets || [])
        .map((b) => (typeof b === 'string' ? { text: b, enabled: true } : b))
        .filter((b) => b && b.enabled !== false && ((typeof b === 'string' && b.trim()) || (b.text && String(b.text).trim()) || (b.bullet && String(b.bullet).trim())));

      if (validBullets.length > 0) {
        out += `      \\resumeItemListStart\n`;
        validBullets.forEach((b) => {
          const rawBullet = typeof b === 'string' ? b : (b.text ?? b.bullet ?? '');
          out += `        \\resumeItem{${escapeLatex(String(rawBullet).trim())}}\n`;
        });
        out += `      \\resumeItemListEnd\n`;
      }
    });
    out += `  \\resumeSubHeadingListEnd\n`;
    return out;
  };

  const renderSkills = () => {
    let validSkills = [];
    if (Array.isArray(skills)) {
      validSkills = skills
        .filter((s) => s && s.enabled !== false)
        .map((s) => ({
          category: String(s.category || s.title || s.name || 'Skills').trim(),
          items: Array.isArray(s.items)
            ? s.items.map((i) => String(i).trim()).filter(Boolean)
            : typeof s.items === 'string'
            ? s.items.split(',').map((it) => it.trim()).filter(Boolean)
            : [],
        }))
        .filter((s) => s.category.length > 0 && s.items.length > 0);
    } else if (skills && typeof skills === 'object') {
      const legacyMap = [
        { category: 'Languages', items: skills.languages },
        { category: 'Frameworks', items: skills.frameworks },
        { category: 'Developer Tools', items: skills.developerTools },
        { category: 'Libraries', items: skills.libraries },
      ];
      validSkills = legacyMap
        .filter((c) => Array.isArray(c.items) && c.items.length > 0)
        .map((c) => ({
          category: c.category,
          items: c.items.map((i) => String(i).trim()).filter(Boolean),
        }))
        .filter((c) => c.items.length > 0);
    }

    if (validSkills.length === 0) return '';
    let out = `\n%-----------TECHNICAL SKILLS-----------\n`;
    out += `\\section{Technical Skills}\n`;
    out += ` \\begin{itemize}[leftmargin=0.15in, label={}]\n`;
    out += `    \\small{\\item{\n`;
    const lines = validSkills.map(
      (s) => `     \\textbf{${escapeLatex(s.category)}}{: ${s.items.map(escapeLatex).join(', ')}}`
    );
    out += lines.join(' \\\\\n') + '\n';
    out += `    }}\n`;
    out += ` \\end{itemize}\n`;
    return out;
  };

  const renderCustomSections = () => {
    let out = '';
    (customSections || []).forEach((sec) => {
      if (!sec || !sec.sectionTitle || sec.enabled === false) return;
      const validItems = (sec.items || []).filter((item) => item && item.enabled !== false);
      if (validItems.length === 0) return;

      out += `\n%-----------${sec.sectionTitle.toUpperCase()}-----------\n`;
      out += `\\section{${escapeLatex(sec.sectionTitle)}}\n`;
      out += `  \\resumeSubHeadingListStart\n`;

      validItems.forEach((item) => {
        // Avoid repeating the title if it matches sectionTitle
        const titleText = (item.title && item.title.toLowerCase() !== sec.sectionTitle.toLowerCase())
          ? item.title
          : (item.subtitle || item.title || '');
        const subText = (item.title && item.title.toLowerCase() !== sec.sectionTitle.toLowerCase() && item.subtitle)
          ? ` $|$ \\emph{${escapeLatex(item.subtitle)}}`
          : '';

        out += `    \\resumeProjectHeading\n`;
        out += `      {\\textbf{${escapeLatex(titleText)}}${subText}}{${escapeLatex(item.date || '')}}\n`;

        const validBullets = (item.bullets || []).filter(
          (b) => b && b.enabled !== false && (b.text || typeof b === 'string')
        );
        if (validBullets.length > 0) {
          out += `      \\resumeItemListStart\n`;
          validBullets.forEach((b) => {
            const bulletText = typeof b === 'string' ? b : (b.text || b.bullet || '');
            if (bulletText && String(bulletText).trim()) {
              out += `        \\resumeItem{${escapeLatex(String(bulletText).trim())}}\n`;
            }
          });
          out += `      \\resumeItemListEnd\n`;
        } else if (item.description && String(item.description).trim()) {
          out += `      \\resumeItemListStart\n`;
          out += `        \\resumeItem{${escapeLatex(String(item.description).trim())}}\n`;
          out += `      \\resumeItemListEnd\n`;
        }
      });

      out += `  \\resumeSubHeadingListEnd\n`;
    });
    return out;
  };

  const sectionRenderers = {
    education: renderEducation,
    experience: renderExperience,
    projects: renderProjects,
    skills: renderSkills,
    customSections: renderCustomSections,
  };

  order.forEach((sectionKey) => {
    const renderer = sectionRenderers[sectionKey];
    if (renderer) {
      tex += renderer();
    }
  });

  tex += `\n\\end{document}\n`;

  return tex;
}
